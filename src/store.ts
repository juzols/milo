import os from "node:os";
import path from "node:path";
import { promises as fs, existsSync } from "node:fs";
import type { ModelMessage } from "ai";

export type Config = { model: string; createdAt: string };
export type SessionFile = {
    id: string;
    startedAt: string;
    updatedAt: string;
    model: string;
    tokens: { input: number; output: number };
    messages: ModelMessage[];
};

export const ROOT = process.cwd();
export const DIR = path.join(ROOT, ".MILO");
const SESSIONS = path.join(DIR, "sessions");
const CONTEXT = path.join(DIR, "context.md");
const MEMORY = path.join(DIR, "memory.md");
const CONFIG = path.join(DIR, "config.json");
const GLOBAL_DIR = path.join(os.homedir(), ".milo");
const GLOBAL_CONFIG = path.join(GLOBAL_DIR, "config.json");

export const DEFAULT_MODEL = "openai/gpt-5.4-nano";
export const IGNORED = new Set([
    "node_modules",
    ".git",
    ".MILO",
    "dist",
    "build",
    ".next",
    ".cache",
]);

export async function getApiKey(): Promise<string | undefined> {
    if (process.env.AI_GATEWAY_API_KEY) return process.env.AI_GATEWAY_API_KEY;

    try {
        return JSON.parse(await fs.readFile(GLOBAL_CONFIG, "utf-8")).apiKey;
    } catch {
        return undefined;
    }
}

export async function saveApiKey(apiKey: string) {
    await fs.mkdir(GLOBAL_DIR, { recursive: true });
    await fs.writeFile(GLOBAL_CONFIG, JSON.stringify({ apiKey }, null, 2), {
        mode: 0o600,
    });
}

async function tree(
    dir: string,
    depth: number,
    prefix = "",
): Promise<string[]> {
    if (depth < 0) return [];

    const entries = (await fs.readdir(dir, { withFileTypes: true }))
        .filter((e) => !IGNORED.has(e.name) && !e.name.startsWith("."))
        .sort(
            (a, b) =>
                Number(b.isDirectory()) - Number(a.isDirectory()) ||
                a.name.localeCompare(b.name),
        )
        .slice(0, 40);

    const lines: string[] = [];

    for (const e of entries) {
        lines.push(`${prefix}${e.name}${e.isDirectory() ? "/" : ""}`);
        if (e.isDirectory())
            lines.push(
                ...(await tree(
                    path.join(dir, e.name),
                    depth - 1,
                    prefix + "  ",
                )),
            );
    }

    return lines;
}

export async function buildContext(): Promise<string> {
    let pkg = "";

    try {
        const p = JSON.parse(
            await fs.readFile(path.join(ROOT, "package.json"), "utf8"),
        );

        pkg = [
            `- nom : ${p.name ?? "?"}`,
            p.scripts ? `- scripts : ${Object.keys(p.scripts).join(", ")}` : "",
            p.dependencies
                ? `- dépendances : ${Object.keys(p.dependencies).slice(0, 15).join(", ")}`
                : "",
        ]
            .filter(Boolean)
            .join("\n");
    } catch {}

    const files = await tree(ROOT, 2);

    return [
        `# Projects Context : ${path.basename(ROOT)}`,
        "",
        "> File generated by milo, editable: it is re-read on every message.",
        "> Add conventions, test commands, style rules here…",
        "",
        pkg ? "## package.json\n" + pkg + "\n" : "",
        "## Structure (2 levels)",
        files.join("\n") || "(empty folder)",
        "",
        "## Notes",
        "- (to be completed)",
        "",
    ].join("\n");
}

export async function initProject(
    model?: string,
): Promise<{ created: boolean; config: Config }> {
    if (existsSync(CONFIG)) {
        const config: Config = JSON.parse(await fs.readFile(CONFIG, "utf-8"));
        if (model) config.model = model;

        return {
            created: false,
            config,
        };
    }

    await fs.mkdir(SESSIONS, { recursive: true });
    await fs.writeFile(path.join(DIR, ".gitignore"), "*\n");

    const config: Config = {
        model: model ?? DEFAULT_MODEL,
        createdAt: new Date().toISOString(),
    };

    await fs.writeFile(CONFIG, JSON.stringify(config, null, 2));
    await fs.writeFile(CONTEXT, await buildContext());
    await fs.writeFile(MEMORY, "# Memory of milo\n\n");

    return { created: true, config };
}

export const saveConfig = (config: Config) =>
    fs.writeFile(CONFIG, JSON.stringify(config, null, 2));
export const regenerateContext = async () =>
    fs.writeFile(CONTEXT, await buildContext());

export async function readContext(): Promise<string> {
    return (
        (await fs.readFile(CONTEXT, "utf8").catch(() => "")) +
        "\n" +
        (await fs.readFile(MEMORY, "utf8").catch(() => ""))
    );
}

export async function appendMemory(note: string) {
    await fs.mkdir(DIR, { recursive: true });

    await fs.appendFile(
        MEMORY,
        `- ${new Date().toISOString().slice(0, 10)} : ${note}\n`,
    );
}

export const newSessionId = () =>
    new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);

export async function saveSession(s: SessionFile) {
    await fs.mkdir(SESSIONS, { recursive: true });

    s.updatedAt = new Date().toISOString();

    await fs.writeFile(
        path.join(SESSIONS, `${s.id}.json`),
        JSON.stringify(s, null, 2),
    );
}

export async function listSessions(): Promise<SessionFile[]> {
    const files = (await fs.readdir(SESSIONS).catch(() => []))
        .filter((f) => f.endsWith(".json"))
        .sort();
    const out: SessionFile[] = [];

    for (const f of files) {
        try {
            out.push(
                JSON.parse(await fs.readFile(path.join(SESSIONS, f), "utf8")),
            );
        } catch {}
    }

    return out;
}

export async function loadLastSession(): Promise<SessionFile | undefined> {
    return (await listSessions()).at(-1);
}
